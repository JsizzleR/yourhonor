#' Example gold-labeled support answers
#'
#' A small synthetic dataset of support-style question/answer items, each rated
#' Incorrect / Partial / Correct by a human and by an example LLM judge. It is
#' the input for the live-judge example in the README and exists to
#' demonstrate the [calibrate_judge()] API without a model call. It is eight
#' items: not a benchmark and not a basis for any deployment decision. The
#' judge labels disagree with the human labels on two items (1 and 7, where
#' the judge is one level more lenient), so agreement is realistic rather
#' than 1.0.
#'
#' @format A tibble with 8 rows and 5 columns:
#' \describe{
#'   \item{id}{Integer item identifier, `1:8`.}
#'   \item{input}{Character. The question and candidate answer presented to the
#'     judge, formatted as `"Question: ...\nAnswer: ..."`.}
#'   \item{target}{Character. The grading criterion; the same sentence for
#'     every item.}
#'   \item{human_label}{Human rating, an ordered factor with levels
#'     `I` < `P` < `C`.}
#'   \item{judge_label}{Example judge rating, same ordered levels.}
#' }
#' @source Generated by `data-raw/support_gold.R`.
#' @examples
#' support_gold
#' calibrate_judge(
#'   support_gold,
#'   id_col = "id",
#'   label_levels = c("I", "P", "C"),
#'   scale = "ordinal",
#'   n_boot = 100,
#'   seed = 1
#' )
"support_gold"

#' Synthetic calibration set with three human raters
#'
#' A 200-item synthetic set of support-style question/answer items, each rated
#' Incorrect / Partial / Correct by three simulated human raters. It is sized
#' so that an audit can reach a verdict rather than stop at `INDETERMINATE`,
#' and it is the input for the README's end-to-end run. Every label is
#' planted: a true label was drawn per item, the answer text written to match
#' it (correct answers name a place and an action, partial answers hedge,
#' incorrect answers deflect), and each rater is the truth with a 6% chance of
#' an adjacent-level slip. The text is templated from 24 questions, so no row
#' is a real ticket; what is independent across rows is the draw of the label
#' and of each rater's error. Inputs are at most 180 characters, so a judge
#' whose behaviour changes above 240 characters is moved by the verbosity
#' probe's filler and not by the shorter framing prefixes of the other probes.
#' Not a benchmark and not a basis for any deployment decision.
#'
#' @format A tibble with 200 rows and 6 columns:
#' \describe{
#'   \item{id}{Character item identifier, `"syn-001"` to `"syn-200"`.}
#'   \item{input}{Character. The question and candidate answer presented to the
#'     judge, formatted as `"Question <n>: ...\nAnswer: ..."`.}
#'   \item{target}{Character. The grading criterion; the same sentence for
#'     every item.}
#'   \item{rater_1, rater_2, rater_3}{Simulated human ratings, ordered factors
#'     with levels `I` < `P` < `C`.}
#' }
#' @source Generated by `data-raw/synthetic_gold.R` with a fixed seed.
#' @examples
#' synthetic_gold
#' calibrate_judge(
#'   synthetic_gold,
#'   human_cols = c("rater_1", "rater_2", "rater_3"),
#'   judge = function(data) {
#'     tibble::tibble(.item_id = data$.item_id, label = rep("C", nrow(data)))
#'   },
#'   input_cols = c("input", "target"),
#'   id_col = "id",
#'   label_levels = c("I", "P", "C"),
#'   scale = "ordinal",
#'   n_boot = 100,
#'   seed = 1
#' )
"synthetic_gold"
